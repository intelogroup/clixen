//! Static checks on the webview attack surface: CSP and per-window command grants.

use serde_json::Value;

fn json(rel: &str) -> Value {
    let p = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(rel);
    serde_json::from_str(&std::fs::read_to_string(&p).unwrap_or_else(|e| panic!("{}: {e}", p.display()))).unwrap()
}

fn perms(cap: &Value) -> Vec<String> {
    cap["permissions"].as_array().unwrap().iter().filter_map(|p| p.as_str().map(String::from)).collect()
}

#[test]
fn csp_blocks_inline_and_eval_script() {
    let conf = json("tauri.conf.json");
    let csp = conf["app"]["security"]["csp"].as_str().expect("a CSP must be set");
    let script = csp.split(';').map(str::trim).find(|d| d.starts_with("script-src")).expect("script-src directive");
    assert!(!script.contains("unsafe-inline") && !script.contains("unsafe-eval") && !script.contains('*'), "script-src too loose: {script}");
    assert!(csp.contains("object-src 'none'") && csp.contains("base-uri 'none'"));
    assert!(csp.starts_with("default-src 'self'"));
}

#[test]
fn orb_windows_cannot_call_lifecycle_commands_and_setup_cannot_drive_the_orb() {
    let orb = json("capabilities/default.json");
    let setup = json("capabilities/setup.json");
    assert!(perms(&orb).iter().all(|p| !p.starts_with("allow-lifecycle-")), "orb windows must not hold lifecycle commands (lock/unlock/uninstall)");
    assert!(perms(&setup).iter().all(|p| !p.starts_with("allow-orb-")), "the setup window must not drive the orb");
    let orb_windows: Vec<&str> = orb["windows"].as_array().unwrap().iter().filter_map(|w| w.as_str()).collect();
    assert!(!orb_windows.contains(&"setup"));
    assert_eq!(setup["windows"], serde_json::json!(["setup"]));
}

#[test]
fn only_the_two_capabilities_are_enabled_and_no_generic_exec_plugin_is_granted() {
    let conf = json("tauri.conf.json");
    assert_eq!(conf["app"]["security"]["capabilities"], serde_json::json!(["orb-capability", "setup-capability"]));
    for f in ["capabilities/default.json", "capabilities/setup.json"] {
        for p in perms(&json(f)) {
            assert!(!p.starts_with("shell:") && !p.starts_with("fs:") && !p.starts_with("http:") && !p.starts_with("opener:"), "{f} grants {p}");
        }
    }
}

#[test]
fn every_granted_command_permission_exists() {
    for f in ["capabilities/default.json", "capabilities/setup.json"] {
        for p in perms(&json(f)).iter().filter(|p| p.starts_with("allow-")) {
            let file = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("permissions/autogenerated").join(format!("{}.toml", p.trim_start_matches("allow-").replace('-', "_")));
            assert!(file.exists(), "{f}: no permission file for {p}: {}", file.display());
        }
    }
}

/// Every `#[tauri::command]` in `src/`, as the name the webview invokes.
fn command_fns() -> Vec<String> {
    let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
    let mut out = Vec::new();
    for entry in std::fs::read_dir(&dir).unwrap() {
        let path = entry.unwrap().path();
        if path.extension().and_then(|e| e.to_str()) != Some("rs") {
            continue;
        }
        let src = std::fs::read_to_string(&path).unwrap();
        let mut lines = src.lines();
        while let Some(line) = lines.next() {
            if line.trim() != "#[tauri::command]" {
                continue;
            }
            for next in lines.by_ref() {
                let t = next.trim_start();
                if t.is_empty() || t.starts_with("//") || t.starts_with("#[") {
                    continue;
                }
                let rest = t.strip_prefix("pub ").unwrap_or(t);
                if let Some(rest) = rest.strip_prefix("async fn ").or_else(|| rest.strip_prefix("fn ")) {
                    out.push(rest.split(['(', '<']).next().unwrap().trim().to_string());
                }
                break;
            }
        }
    }
    out
}

/// The names registered in `build.rs`; only these get an `allow-*` permission.
fn build_commands() -> Vec<String> {
    let p = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("build.rs");
    let src = std::fs::read_to_string(&p).unwrap();
    let list = src
        .split("const COMMANDS: &[&str] = &[")
        .nth(1)
        .expect("build.rs must define COMMANDS")
        .split(']')
        .next()
        .unwrap();
    list.split('"').skip(1).step_by(2).map(String::from).collect()
}

#[test]
fn every_command_is_registered_in_build_rs_and_granted_by_a_capability() {
    let mut found = command_fns();
    found.sort();
    let mut listed = build_commands();
    listed.sort();

    let missing: Vec<_> = found.iter().filter(|c| !listed.contains(c)).collect();
    assert!(missing.is_empty(), "commands missing from build.rs COMMANDS (invoking them fails with \"not allowed by ACL\"): {missing:?}");

    let stale: Vec<_> = listed.iter().filter(|c| !found.contains(c)).collect();
    assert!(stale.is_empty(), "build.rs lists commands that no longer exist: {stale:?}");

    let mut granted = Vec::new();
    for f in ["capabilities/default.json", "capabilities/setup.json"] {
        granted.extend(perms(&json(f)));
    }
    let ungranted: Vec<_> = found
        .iter()
        .filter(|c| !granted.contains(&format!("allow-{}", c.replace('_', "-"))))
        .collect();
    assert!(ungranted.is_empty(), "commands not granted by any capability (invoking them fails with \"not allowed by ACL\"): {ungranted:?}");
}

#[test]
fn hardened_runtime_on_and_entitlements_are_the_minimum() {
    let conf = json("tauri.conf.json");
    assert_eq!(conf["bundle"]["macOS"]["hardenedRuntime"], true);
    let plist = std::fs::read_to_string(std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("Entitlements.plist")).unwrap();
    let keys: Vec<&str> = plist.split("<key>").skip(1).filter_map(|k| k.split("</key>").next()).collect();
    let allowed = ["com.apple.security.device.audio-input", "com.apple.security.automation.apple-events"];
    assert!(keys.iter().all(|k| allowed.contains(k)), "unexpected entitlement in {keys:?}");
    for banned in ["files.all", "allow-jit", "disable-library-validation", "allow-unsigned-executable-memory"] {
        assert!(!plist.contains(banned), "{banned} must not be granted");
    }
}
